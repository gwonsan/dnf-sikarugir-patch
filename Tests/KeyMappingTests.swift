import Foundation

func expect(_ ok: @autoclosure () -> Bool, _ message: String) {
    if !ok() { fputs("FAIL: \(message)\n", stderr); exit(1) }
}
@main struct KeyMappingTests {
    static func main() throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent("DNF keyboard \(UUID())")
        defer { try? FileManager.default.removeItem(at: root) }
        let wrapper = root.appendingPathComponent("Apps With Spaces/DNF.app")
        let store = KeyProfileStore(directory: root.appendingPathComponent("profiles"))
        var profile = KeyProfile(wrapperPath: wrapper.path)
        expect(!profile.enabled && profile.bindings.isEmpty, "default must not intercept keys")
        profile.bindings = [.init(source: 0, target: .key(8)), .init(source: 8, target: .key(0))]
        try store.save(profile)
        let loaded = try store.load(wrapper: wrapper)
        expect(loaded == profile, "round-trip swaps atomically without modifying wrapper")
        let other = try store.load(wrapper: root.appendingPathComponent("Other.app"))
        expect(other.bindings.isEmpty, "another wrapper never inherits a profile")
        var invalid = profile
        invalid.bindings.append(.init(source: 0, target: .disabled))
        do { try store.save(invalid); expect(false, "duplicate sources rejected") } catch {}
        invalid = profile; invalid.bindings = [.init(source: 999, target: .key(0))]
        do { try store.save(invalid); expect(false, "unknown physical key rejected") } catch {}
        invalid = profile; invalid.version = 99
        do { try store.save(invalid); expect(false, "unknown schema rejected") } catch {}
        let preserved = try store.load(wrapper: wrapper)
        expect(preserved == profile, "invalid save preserves existing profile")

        let delivered = KeyMappingState(bindings:[.init(source:0,target:.key(8)),.init(source:8,target:.key(2))])
        expect(delivered.deliver(source:0,target:.key(11),down:true) == [.down(11)],"Karabiner-selected semantic target is delivered directly, not looked up or remapped again")
        expect(delivered.deliver(source:0,target:.key(11),down:false) == [.up(11)],"semantic release matches delivered press")
        let rawRelease = KeyMappingState(bindings:[.init(source:59,target:.key(59)),.init(source:0,target:.key(59))],initiallyHeld:[59])
        expect(rawRelease.rewriteFlags(0) & 0x40001 == 0x40001,"pre-held Control is initially adopted")
        _ = rawRelease.deliver(source:59,target:.key(59),down:false)
        expect(rawRelease.rewriteFlags(0) & 0x40001 == 0,"raw pre-session release clears seeded Control without remapping")
        let rawIdentity = KeyMappingState(bindings:[.init(source:0,target:.key(11))])
        expect(rawIdentity.deliver(source:0,target:.key(0),down:true) == [.down(0)],"raw synthetic input bypassing Karabiner keeps identity")
        var aloneState = KeyAloneState()
        aloneState.begin(61)
        expect(!aloneState.nativeVerdict(61,eligible:true),"native standalone eligibility alone cannot toggle")
        expect(aloneState.karabinerVerdict(61,held:false),"both standalone verdicts toggle exactly once")
        expect(!aloneState.karabinerVerdict(61,held:false),"duplicate standalone message never toggles")
        aloneState.begin(61)
        expect(!aloneState.karabinerVerdict(61,held:true),"core verdict may arrive before native key-up")
        expect(!aloneState.nativeVerdict(61,eligible:false),"previously-held modifier prevents an otherwise-alone core verdict")
        aloneState.clear()
        expect(!aloneState.karabinerVerdict(61,held:false),"focus loss rejects a stale standalone completion")
        var repeatState = KeyRepeatState(delay:0.3,interval:0.04)
        repeatState.update(source:0,target:.key(11),down:true,now:1)
        expect(repeatState.due(now:1.2) == nil,"repeat waits for system initial delay")
        expect(repeatState.due(now:1.31)?.source == 0,"held semantic letter repeats after delay")
        repeatState.update(source:8,target:.key(2),down:true,now:1.4)
        expect(repeatState.due(now:1.5) == nil,"newest held letter owns repeat timing")
        repeatState.clear()
        expect(repeatState.due(now:5) == nil,"focus loss cancels all owned repeats")
        let state = KeyMappingState(bindings: profile.bindings)
        expect(state.handle(0, down: true) == [.down(8)], "A maps to C without recursively mapping C back")
        expect(state.handle(0, down: true, repeating: true) == [.down(8)], "repeat preserves mapped key")
        expect(state.handle(0, down: false) == [.up(8)], "release matches original press")
        let duplicate = KeyMappingState(bindings: [.init(source: 0, target: .key(8)), .init(source: 1, target: .key(8))])
        expect(duplicate.handle(0, down: true) == [.down(8)], "first source presses target")
        expect(duplicate.handle(1, down: true).isEmpty, "second source shares held target")
        expect(duplicate.handle(0, down: false).isEmpty, "one source cannot release another")
        expect(duplicate.releaseAll() == [.up(8)], "focus loss releases held output once")
        expect(duplicate.handle(1, down: false).isEmpty, "late release after focus loss is ignored")

        let mixed = KeyMappingState(bindings: [.init(source: 0, target: .key(8))])
        expect(mixed.maps(8), "unmapped physical target participates in ownership")
        expect(mixed.handle(0, down:true) == [.down(8)], "mapped source presses C")
        expect(mixed.handle(8, down:true).isEmpty, "physical C shares the mapped target")
        expect(mixed.handle(0, down:false).isEmpty, "mapped release preserves physical C")
        expect(mixed.handle(8, down:false) == [.up(8)], "last physical release releases C")
        let mixedModifier = KeyMappingState(bindings:[.init(source:0,target:.key(59))])
        _ = mixedModifier.handle(0,down:true); _ = mixedModifier.handle(59,down:true)
        expect(mixedModifier.handle(59,down:false).isEmpty && mixedModifier.rewriteFlags(0) & 0x40001 == 0x40001, "physical Control release cannot cancel mapped Control")

        let entryTarget = KeyMappingState(bindings:[.init(source:0,target:.key(8))], initiallyHeld:[8])
        expect(entryTarget.handle(0,down:true).isEmpty, "held native C already owns C")
        expect(entryTarget.handle(0,down:false).isEmpty, "A release cannot release initially held C")
        expect(!entryTarget.intercepts(8,down:false), "last initial C release passes through")
        expect(entryTarget.handle(8,down:false).isEmpty, "pass-through release is not duplicated")
        let entryReverse = KeyMappingState(bindings:[.init(source:0,target:.key(8))], initiallyHeld:[8])
        _ = entryReverse.handle(0,down:true)
        expect(entryReverse.intercepts(8,down:false), "native C-up must be suppressed while A owns C")
        expect(entryReverse.handle(8,down:false).isEmpty && entryReverse.handle(0,down:false) == [.up(8)], "A releases the adopted target last")
        let entryControl = KeyMappingState(bindings:[.init(source:0,target:.key(59))], initiallyHeld:[59])
        _ = entryControl.handle(0,down:true)
        expect(entryControl.handle(0,down:false).isEmpty && entryControl.rewriteFlags(0x40001) & 0x40001 == 0x40001, "initial Control remains held after mapped A release")
        let untouchedEntry = KeyMappingState(bindings:[.init(source:0,target:.key(8))], initiallyHeld:[8])
        expect(untouchedEntry.releaseAll().isEmpty, "focus loss does not release an unowned initial key")

        var sourceGuard = KeyInputSourceGuard(source:"Korean")
        expect(sourceGuard.sourceChanged("ABC", now:10) == nil, "source notification may precede HID input")
        expect(sourceGuard.capsDown(now:10.05) == "Korean", "late HID callback must restore immediately")
        sourceGuard = KeyInputSourceGuard(source:"Korean")
        expect(sourceGuard.capsDown(now:20) == nil, "HID before source change needs no immediate restore")
        expect(sourceGuard.sourceChanged("ABC",now:20.1) == "Korean", "subsequent source notification restores guarded source")
        sourceGuard.intentionalSwitch("ABC")
        expect(sourceGuard.sourceChanged("ABC",now:21) == nil && sourceGuard.capsDown(now:21.05) == nil, "intentional Option switch is never rolled back")

        let standalone = KeyMappingState(bindings:[.init(source:61,target:.toggleInputSource)])
        _ = standalone.handle(59,down:true); _ = standalone.handle(61,down:true)
        expect(standalone.handle(61,down:false).isEmpty, "a modifier held before Option prevents standalone switching")
        let seeded = KeyMappingState(bindings:[.init(source:61,target:.toggleInputSource)], initiallyHeld:[59])
        _ = seeded.handle(61,down:true)
        expect(seeded.handle(61,down:false).isEmpty, "modifiers held during activation prevent standalone switching")
        let alreadyHeld = KeyMappingState(bindings:[.init(source:55,target:.key(59))], initiallyHeld:[55])
        expect(!alreadyHeld.intercepts(55), "a key held in another app is not captured midway")
        _ = alreadyHeld.handle(55,down:false)
        expect(alreadyHeld.intercepts(55) && alreadyHeld.handle(55,down:true) == [.down(59)], "mapping arms after initial physical release")

        let caps = KeyMappingState(bindings: [.init(source: 57, target: .key(57)), .init(source: 61, target: .toggleInputSource)])
        expect(caps.handle(57, down: true) == [.caps(true)], "physical Caps press produces one local lock transition")
        expect(caps.handle(57, down: true, repeating: true).isEmpty, "Caps repeat never toggles lock")
        expect(caps.handle(57, down: false).isEmpty, "Caps release never toggles lock")
        expect(caps.handle(61, down: true).isEmpty, "input source waits for a tap release")
        expect(caps.handle(61, down: false) == [.inputSource], "Option tap toggles input source once")
        _ = caps.handle(61, down: true); _ = caps.handle(0, down: true)
        expect(caps.handle(61, down: false).isEmpty, "Option chord does not switch source")
        expect(caps.releaseAll() == [.caps(false)], "stop clears owned virtual Caps state")

        let modifiers = KeyMappingState(bindings: [.init(source: 55, target: .key(59))])
        _ = modifiers.handle(55, down: true)
        let flags = modifiers.rewriteFlags(0x100008)
        expect(flags & 0x100008 == 0 && flags & 0x40001 == 0x40001, "Command-to-Control rewrites both generic and side flags")
        expect(modifiers.releaseAll() == [.up(59)], "focus loss releases mapped Control")
        let scoped = wrapper.appendingPathComponent("Contents/SharedSupport/prefix/drive_c/Program Files (x86)/DNF/DNF.exe").path
        expect(KeyScope.accepts(processExecutable: "C:\\DNF\\DNF.exe", mappedPaths: [scoped], wrapper: wrapper), "exact wrapper game mapping is accepted")
        expect(!KeyScope.accepts(processExecutable: "C:\\DNF\\DNF.exe", mappedPaths: [scoped.replacingOccurrences(of: "DNF.exe", with: "NeopleLauncher.exe")], wrapper: wrapper), "launcher is not game")
        expect(!KeyScope.accepts(processExecutable: "C:\\DNF\\DNF.exe", mappedPaths: [scoped], wrapper: root.appendingPathComponent("Other.app")), "other wrapper is rejected")
        expect(!KeyScope.accepts(processExecutable: "C:\\DNF\\NeopleLauncher.exe", mappedPaths: [scoped], wrapper: wrapper), "a launcher checking the game file is not the game process")
        expect(KeyScope.matchesEvent(frontmost: 101, eventTarget: 101, attested: 101), "attested foreground accepts its own event")
        expect(!KeyScope.matchesEvent(frontmost: 202, eventTarget: 101, attested: 101), "focus switch blocks late events")
        expect(!KeyScope.matchesEvent(frontmost: 101, eventTarget: 202, attested: 101), "another process event is untouched")
        expect(!KeyScope.matchesEvent(frontmost: 101, eventTarget: 0, attested: 101), "unknown event target fails open")
        print("PASS: keyboard persistence, validation, swaps, repeats, shared targets, Caps, modifiers, focus release and DNF scope")
    }
}
