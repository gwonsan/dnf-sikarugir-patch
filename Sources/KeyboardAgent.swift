import AppKit
import Carbon
import IOKit.hid
import IOKit.hidsystem
import Darwin

enum KeyboardService {
    static var store: KeyProfileStore { KeyProfileStore(directory: Installer.support.appendingPathComponent("Keyboard")) }
    static var permitted: Bool { AXIsProcessTrusted() && CGPreflightListenEventAccess() }
    static func requestPermission() {
        _ = AXIsProcessTrustedWithOptions([kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary)
        _ = CGRequestListenEventAccess()
    }
    static func startIfEnabled(wrapper: URL, executable: URL? = Bundle.main.executableURL) throws {
        guard try store.load(wrapper: wrapper).enabled else { return }
        try launch(arguments:["--keyboard-agent",wrapper.path], executable:executable)
    }
    static func openPermissionRequest(wrapper: URL) throws {
        try launch(arguments:["--keyboard-permissions",wrapper.path], executable:Bundle.main.executableURL)
    }
    private static func launch(arguments: [String], executable: URL?) throws {
        guard let executable else { throw KeyMappingError(message: "키보드 보정기 실행 경로를 찾지 못했습니다.") }
        let owner = executable.deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
        let agent = owner.appendingPathComponent("Contents/Resources/DNF Keyboard.app")
        guard Bundle(url:agent)?.bundleIdentifier == "io.github.dnf-sikarugir-patch.keyboard" else {
            throw KeyMappingError(message: "동봉한 DNF Keyboard.app이 없습니다. 개발 ZIP 전체를 다시 압축 해제해 주세요.")
        }
        // Launch Services gives the bundled agent its own stable TCC identity, rather than Terminal's.
        guard try Installer.run(URL(fileURLWithPath:"/usr/bin/open"), ["-n","-g",agent.path,"--args"] + arguments, timeout:10) == 0 else {
            throw KeyMappingError(message: "키보드 보정기를 시작하지 못했습니다.")
        }
    }
    static func configurePermissions(wrapper: URL) {
        try? FileManager.default.createDirectory(at:store.directory,withIntermediateDirectories:true,attributes:[.posixPermissions:0o700])
        requestPermission()
        _ = NSWorkspace.shared.open(URL(string:"x-apple.systempreferences:com.apple.preference.security?Privacy_ListenEvent")!)
        let deadline = Date(timeIntervalSinceNow:120)
        while !permitted && Date() < deadline { _ = RunLoop.current.run(mode:.default,before:Date(timeIntervalSinceNow:0.2)) }
        if let data = try? JSONEncoder().encode(KeyboardStatus(updated:Date(),message:permitted ? "권한 허용됨 · TUI에서 S 저장으로 시작" : "입력 모니터링·손쉬운 사용 권한 확인 필요",running:false)) {
            try? data.write(to:statusURL(wrapper:wrapper),options:.atomic)
        }
    }
    static func statusURL(wrapper: URL) -> URL { store.url(wrapper: wrapper).appendingPathExtension("status.json") }
    static func status(wrapper: URL) -> String {
        guard let data = try? Data(contentsOf: statusURL(wrapper: wrapper)),
              let status = try? JSONDecoder().decode(KeyboardStatus.self, from: data),
              !status.running || Date().timeIntervalSince(status.updated) < 4 else { return "보정기 대기 · S 시작 / P 권한 설정" }
        return status.message
    }
}

private struct KeyboardStatus: Codable {
    let updated: Date
    let message: String
    let running: Bool
}

/// Runs in the shipped helper, not in a global login item or a keyboard driver.
final class KeyboardAgent {
    private let wrapper: URL
    private var profile: KeyProfile
    private var state: KeyMappingState
    private var target: pid_t = 0
    private var checkedPID: pid_t = 0
    private var checkedAt = Date.distantPast
    private var attestationInFlight = false
    private var gamePID: pid_t = 0
    private var tap: CFMachPort?
    private var hid: IOHIDManager?
    private var capsDevices = Set<UInt64>()
    private var sourceGuard = KeyInputSourceGuard(source:nil)
    private var sourcesByID: [String:TISInputSource] = [:]
    private var sourceObserver: NSObjectProtocol?
    private var signalSources: [DispatchSourceSignal] = []
    private var active = true
    private var suspended = false
    private var stopMessage = "키보드 보정 종료"
    private var capsAtEntry: Bool?
    private var seenGame = false
    private var lastGame = Date()
    private let started = Date()
    // Ignore only events generated by this process. Never inspect or log their text.
    private let marker = Int64.random(in: 1...Int64.max)

    init(wrapper: URL) throws {
        self.wrapper = wrapper.standardizedFileURL.resolvingSymlinksInPath()
        profile = try KeyboardService.store.load(wrapper: self.wrapper)
        state = KeyMappingState(bindings: profile.bindings)
    }

    func run() throws {
        guard profile.enabled else { return }
        guard KeyboardService.permitted else {
            report("권한이 없어 키 매핑을 시작하지 않았습니다.", running: false)
            throw KeyMappingError(message: "시스템 설정 → 개인정보 보호 및 보안에서 DNF Keyboard의 손쉬운 사용과 입력 모니터링을 허용해 주세요.")
        }
        let lockURL = KeyboardService.store.url(wrapper: wrapper).appendingPathExtension("lock")
        let descriptor = open(lockURL.path, O_CREAT | O_RDWR | O_NOFOLLOW, 0o600)
        guard descriptor >= 0 else { throw KeyMappingError(message: "키보드 보정 잠금 파일을 열지 못했습니다.") }
        defer { close(descriptor) }
        guard flock(descriptor, LOCK_EX | LOCK_NB) == 0 else { return }
        defer { flock(descriptor, LOCK_UN) }
        let types: [CGEventType] = [.keyDown,.keyUp,.flagsChanged,.mouseMoved,.leftMouseDown,.leftMouseUp,.rightMouseDown,.rightMouseUp,.otherMouseDown,.otherMouseUp,.leftMouseDragged,.rightMouseDragged,.scrollWheel]
        let mask = types.reduce(CGEventMask(0)) { $0 | (1 << $1.rawValue) }
        guard let tap = CGEvent.tapCreate(tap: .cgAnnotatedSessionEventTap, place: .headInsertEventTap, options: .defaultTap, eventsOfInterest: mask, callback: { _, type, event, context in
            guard let context else { return Unmanaged.passUnretained(event) }
            return Unmanaged<KeyboardAgent>.fromOpaque(context).takeUnretainedValue().filter(type: type, event: event)
        }, userInfo: Unmanaged.passUnretained(self).toOpaque()) else {
            report("입력 캡처를 시작하지 못했습니다. 권한을 확인해 주세요.", running: false)
            throw KeyMappingError(message: "키보드 입력 캡처를 만들지 못했습니다.")
        }
        self.tap = tap
        let source = CFMachPortCreateRunLoopSource(kCFAllocatorDefault, tap, 0)
        CFRunLoopAddSource(CFRunLoopGetMain(), source, .commonModes)
        CGEvent.tapEnable(tap: tap, enable: false)
        sourceObserver = DistributedNotificationCenter.default().addObserver(forName: Notification.Name(kTISNotifySelectedKeyboardInputSourceChanged as String), object: nil, queue: .main) { [weak self] _ in self?.inputSourceChanged() }
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.refresh() }
        RunLoop.main.add(timer, forMode: .common)
        for number in [SIGTERM, SIGINT, SIGHUP] {
            signal(number, SIG_IGN)
            let source = DispatchSource.makeSignalSource(signal: number, queue: .main)
            source.setEventHandler { [weak self] in self?.active = false }
            source.resume(); signalSources.append(source)
        }
        defer {
            timer.invalidate(); leaveTarget()
            if let sourceObserver { DistributedNotificationCenter.default().removeObserver(sourceObserver) }
            signalSources.forEach { $0.cancel() }
            CFMachPortInvalidate(tap)
            report(suspended ? "긴급 단축키로 일시 중지됨 · TUI에서 다시 실행" : stopMessage, running: false)
        }
        refresh()
        while active { _ = RunLoop.current.run(mode: .default, before: Date(timeIntervalSinceNow: 0.2)) }
    }

    private func report(_ message: String, running: Bool = true) {
        if let data = try? JSONEncoder().encode(KeyboardStatus(updated: Date(), message: message, running: running)) {
            try? data.write(to: KeyboardService.statusURL(wrapper: wrapper), options: .atomic)
        }
    }
    private func refresh() {
        do {
            let latest = try KeyboardService.store.load(wrapper: wrapper)
            if latest != profile { leaveTarget(); profile = latest; state = KeyMappingState(bindings: latest.bindings); checkedAt = .distantPast }
            guard latest.enabled, KeyboardService.permitted else { active = false; return }
        } catch { stopMessage = "키 매핑 파일 오류 · 입력 보정 중지"; active = false; return }
        let front = NSWorkspace.shared.frontmostApplication
        let pid = front?.processIdentifier ?? 0
        if target != 0 && pid != target { leaveTarget() }
        if !attestationInFlight && (pid != checkedPID || Date().timeIntervalSince(checkedAt) > 2) {
            checkedPID = pid; checkedAt = Date()
            let name = front?.executableURL?.lastPathComponent.lowercased() ?? ""
            if pid > 0 && (name.contains("wine") || front?.localizedName?.lowercased().contains("dnf") == true) {
                attestationInFlight = true
                // DNF can map thousands of pack files. Never block the event-tap run loop on lsof.
                DispatchQueue.global(qos:.utility).async { [weak self] in
                    guard let self else { return }
                    let accepted = self.attest(pid)
                    DispatchQueue.main.async {
                        self.attestationInFlight = false
                        guard self.active, NSWorkspace.shared.frontmostApplication?.processIdentifier == pid else { return }
                        if accepted {
                            if self.target != pid { self.enterTarget(pid) }
                            self.seenGame = true; self.gamePID = pid; self.lastGame = Date()
                        } else if self.target == pid { self.leaveTarget() }
                    }
                }
            } else if target == pid { leaveTarget() }
        }
        guard active else { return }
        if target != 0 { lastGame = Date(); restoreHardwareCapsIfNeeded() }
        if seenGame && target == 0 && Date().timeIntervalSince(lastGame) > 8 && kill(gamePID,0) != 0 && errno == ESRCH { active = false }
        if !seenGame && Date().timeIntervalSince(started) > 3 * 60 * 60 { active = false }
        report(target == 0 ? "던파 포커스 대기 · 다른 앱에는 적용 안 함" : "던파에 적용 중 · Ctrl+Option+Esc 긴급 중지")
    }
    private func attest(_ pid: pid_t) -> Bool {
        let identity = Process(); identity.executableURL = URL(fileURLWithPath: "/bin/ps")
        // `comm` is the executable name only: never request args/authentication URLs.
        identity.arguments = ["-p", String(pid), "-o", "comm="]
        let names = Pipe(); identity.standardOutput = names; identity.standardError = FileHandle.nullDevice
        guard (try? identity.run()) != nil else { return false }
        let identityTimeout = DispatchWorkItem { if identity.isRunning { identity.terminate() } }
        DispatchQueue.global(qos:.utility).asyncAfter(deadline:.now()+3,execute:identityTimeout)
        defer { identityTimeout.cancel() }
        let executable = String(decoding:names.fileHandleForReading.readDataToEndOfFile(), as:UTF8.self)
        identity.waitUntilExit()
        guard executable.trimmingCharacters(in:.whitespacesAndNewlines).split(whereSeparator: { $0 == "/" || $0 == "\\" }).last?.lowercased() == "dnf.exe" else { return false }
        let process = Process(); process.executableURL = URL(fileURLWithPath: "/usr/sbin/lsof")
        process.arguments = ["-a", "-p", String(pid), "-Fn"]
        let pipe = Pipe(); process.standardOutput = pipe; process.standardError = FileHandle.nullDevice
        guard (try? process.run()) != nil else { return false }
        let timeout = DispatchWorkItem { if process.isRunning { process.terminate() } }
        DispatchQueue.global(qos:.utility).asyncAfter(deadline:.now()+3,execute:timeout)
        defer { timeout.cancel() }
        let data = pipe.fileHandleForReading.readDataToEndOfFile(); process.waitUntilExit()
        let paths = String(decoding: data, as: UTF8.self).split(separator: "\n").filter { $0.hasPrefix("n/") }.map { String($0.dropFirst()) }
        return KeyScope.accepts(processExecutable: executable, mappedPaths: paths, wrapper: wrapper)
    }
    private func enterTarget(_ pid: pid_t) {
        target = pid
        let initiallyHeld = Set(KeyCatalog.keys.map(\.code).filter { $0 != 57 && CGEventSource.keyState(.hidSystemState, key: CGKeyCode($0)) })
        state = KeyMappingState(bindings: profile.bindings, initiallyHeld: initiallyHeld)
        if let source = TISCopyCurrentKeyboardInputSource()?.takeRetainedValue() {
            sourcesByID[sourceID(source)] = source
            sourceGuard = KeyInputSourceGuard(source:sourceID(source))
        }
        capsAtEntry = hardwareCaps()
        if state.usesCapsLock, !startHID() {
            stopMessage = "Caps Lock 물리 입력을 읽지 못했습니다. 입력 모니터링 권한을 확인해 주세요."
            active = false; return
        }
        if let tap { CGEvent.tapEnable(tap: tap, enable: true) }
    }
    private func leaveTarget() {
        if let tap { CGEvent.tapEnable(tap: tap, enable: false) }
        if let hid {
            IOHIDManagerUnscheduleFromRunLoop(hid, CFRunLoopGetMain(), CFRunLoopMode.commonModes.rawValue)
            IOHIDManagerClose(hid, IOOptionBits(kIOHIDOptionsTypeNone)); self.hid = nil
        }
        emit(state.releaseAll(), pid: target, rawFlags: 0)
        restoreHardwareCapsIfNeeded()
        capsDevices.removeAll(); capsAtEntry = nil
        target = 0; sourcesByID.removeAll(); sourceGuard = KeyInputSourceGuard(source:nil)
    }
    private func startHID() -> Bool {
        let manager = IOHIDManagerCreate(kCFAllocatorDefault, IOOptionBits(kIOHIDOptionsTypeNone))
        IOHIDManagerSetDeviceMatching(manager, [kIOHIDDeviceUsagePageKey: 1, kIOHIDDeviceUsageKey: 6] as CFDictionary)
        IOHIDManagerRegisterInputValueCallback(manager, { context, _, _, value in
            guard let context else { return }
            let element = IOHIDValueGetElement(value)
            guard IOHIDElementGetUsagePage(element) == 7, IOHIDElementGetUsage(element) == 0x39 else { return }
            let agent = Unmanaged<KeyboardAgent>.fromOpaque(context).takeUnretainedValue()
            var identity: UInt64 = 0
            let device = IOHIDElementGetDevice(element)
            IORegistryEntryGetRegistryEntryID(IOHIDDeviceGetService(device), &identity)
            agent.caps(device: identity, down: IOHIDValueGetIntegerValue(value) != 0)
        }, Unmanaged.passUnretained(self).toOpaque())
        IOHIDManagerScheduleWithRunLoop(manager, CFRunLoopGetMain(), CFRunLoopMode.commonModes.rawValue)
        guard IOHIDManagerOpen(manager, IOOptionBits(kIOHIDOptionsTypeNone)) == kIOReturnSuccess else {
            IOHIDManagerUnscheduleFromRunLoop(manager, CFRunLoopGetMain(), CFRunLoopMode.commonModes.rawValue); return false
        }
        hid = manager; return true
    }
    private func caps(device: UInt64, down: Bool) {
        guard target > 0, NSWorkspace.shared.frontmostApplication?.processIdentifier == target, state.maps(57) else { return }
        let wasDown = !capsDevices.isEmpty
        if down { capsDevices.insert(device) } else { capsDevices.remove(device) }
        let isDown = !capsDevices.isEmpty
        guard wasDown != isDown else { return }
        if down {
            if let restore = sourceGuard.capsDown(now:ProcessInfo.processInfo.systemUptime) { restoreSource(restore) }
        }
        emit(state.handle(57, down: isDown), pid: target, rawFlags: CGEventSource.flagsState(.combinedSessionState).rawValue)
        if !down { restoreHardwareCapsIfNeeded() }
    }
    private func filter(type: CGEventType, event: CGEvent) -> Unmanaged<CGEvent>? {
        if type == .tapDisabledByTimeout || type == .tapDisabledByUserInput {
            stopMessage = "입력 캡처가 중단되어 안전하게 보정을 종료했습니다."
            leaveTarget(); active = false; return Unmanaged.passUnretained(event)
        }
        if event.getIntegerValueField(.eventSourceUserData) == marker { return Unmanaged.passUnretained(event) }
        guard KeyScope.matchesEvent(frontmost: NSWorkspace.shared.frontmostApplication?.processIdentifier ?? 0,
                                    eventTarget: event.getIntegerValueField(.eventTargetUnixProcessID), attested: target) else {
            if target != 0 && NSWorkspace.shared.frontmostApplication?.processIdentifier != target { leaveTarget() }
            return Unmanaged.passUnretained(event)
        }
        let raw = event.flags.rawValue
        let code = UInt16(clamping: event.getIntegerValueField(.keyboardEventKeycode))
        if type == .keyDown, code == 53, raw & 0xc0000 == 0xc0000 {
            suspended = true; leaveTarget(); active = false; return nil
        }
        if type == .flagsChanged, code == 57, state.maps(57) { return nil }
        var down: Bool?
        if type == .keyDown { down = true }
        if type == .keyUp { down = false }
        if type == .flagsChanged, let mod = KeyCatalog.modifiers[code] {
            let pressed = raw & mod.side != 0
            down = pressed
        }
        if let down {
            let intercept = state.intercepts(code, down:down)
            let outputs = state.handle(code, down: down, repeating: event.getIntegerValueField(.keyboardEventAutorepeat) != 0)
            if intercept { emit(outputs, pid: target, rawFlags: raw, repeating:event.getIntegerValueField(.keyboardEventAutorepeat) != 0); return nil }
        }
        event.flags = CGEventFlags(rawValue: state.rewriteFlags(raw))
        return Unmanaged.passUnretained(event)
    }
    private func emit(_ outputs: [MappedKeyEvent], pid: pid_t, rawFlags: UInt64, repeating: Bool = false) {
        guard pid > 0 else { return }
        for output in outputs {
            if output == .inputSource {
                if NSWorkspace.shared.frontmostApplication?.processIdentifier == pid { toggleInputSource() }
                continue
            }
            let code: UInt16; let down: Bool; var flags = state.rewriteFlags(rawFlags)
            switch output {
            case .down(let key): code = key; down = true
            case .up(let key):
                code = key; down = false
                if let mod = KeyCatalog.modifiers[key] { flags &= ~mod.side; if !state.activeModifiers.contains(where: { KeyCatalog.modifiers[$0]?.generic == mod.generic }) { flags &= ~mod.generic } }
            case .caps(let locked): code = 57; down = locked; flags = locked ? flags | 0x10000 : flags & ~UInt64(0x10000)
            case .inputSource: continue
            }
            guard let event = CGEvent(keyboardEventSource: nil, virtualKey: CGKeyCode(code), keyDown: down) else { continue }
            if KeyCatalog.modifiers[code] != nil || code == 57 { event.type = .flagsChanged }
            event.flags = CGEventFlags(rawValue: flags)
            event.setIntegerValueField(.keyboardEventAutorepeat, value: down && repeating ? 1 : 0)
            event.setIntegerValueField(.eventSourceUserData, value: marker)
            event.postToPid(pid)
        }
    }
    private func sourceID(_ source: TISInputSource) -> String {
        guard let value = TISGetInputSourceProperty(source, kTISPropertyInputSourceID) else { return "" }
        return Unmanaged<CFString>.fromOpaque(value).takeUnretainedValue() as String
    }
    private func inputSourceChanged() {
        guard target > 0, NSWorkspace.shared.frontmostApplication?.processIdentifier == target,
              let current = TISCopyCurrentKeyboardInputSource()?.takeRetainedValue() else { return }
        let id = sourceID(current); sourcesByID[id] = current
        if let restore = sourceGuard.sourceChanged(id,now:ProcessInfo.processInfo.systemUptime) { restoreSource(restore) }
    }
    private func restoreSource(_ id: String) {
        guard target > 0, NSWorkspace.shared.frontmostApplication?.processIdentifier == target,
              let source = sourcesByID[id] else { return }
        _ = TISSelectInputSource(source)
    }
    private func toggleInputSource() {
        guard let current = TISCopyCurrentKeyboardInputSource()?.takeRetainedValue(),
              let sources = TISCreateInputSourceList([kTISPropertyInputSourceIsSelectCapable: true] as CFDictionary, false)?.takeRetainedValue() as? [TISInputSource] else { return }
        let korean = sourceID(current).hasPrefix("com.apple.inputmethod.Korean")
        let selected = sources.first { source in
            let id = sourceID(source)
            return korean ? ["com.apple.keylayout.ABC", "com.apple.keylayout.US"].contains(id) : id == "com.apple.inputmethod.Korean.2SetKorean"
        }
        if let selected, TISSelectInputSource(selected) == noErr { sourcesByID[sourceID(selected)] = selected; sourceGuard.intentionalSwitch(sourceID(selected)) }
    }
    private func withHIDConnection<T>(_ operation: (io_connect_t) -> T) -> T? {
        let service = IOServiceGetMatchingService(kIOMainPortDefault, IOServiceMatching("IOHIDSystem"))
        guard service != 0 else { return nil }; defer { IOObjectRelease(service) }
        var connection: io_connect_t = 0
        guard IOServiceOpen(service, mach_task_self_, UInt32(kIOHIDParamConnectType), &connection) == KERN_SUCCESS else { return nil }
        defer { IOServiceClose(connection) }
        return operation(connection)
    }
    private func hardwareCaps() -> Bool? {
        withHIDConnection { connection -> Bool? in
            var locked = false
            return IOHIDGetModifierLockState(connection, Int32(kIOHIDCapsLockState), &locked) == KERN_SUCCESS ? locked : nil
        } ?? nil
    }
    private func restoreHardwareCapsIfNeeded() {
        guard state.maps(57), let original = capsAtEntry, let current = hardwareCaps(), current != original else { return }
        _ = withHIDConnection { IOHIDSetModifierLockState($0, Int32(kIOHIDCapsLockState), original) }
    }
}
